package wireguard

import (
	"errors"
	"fmt"
	"net"
	"strings"

	"golang.zx2c4.com/wireguard/wgctrl/wgtypes"
)

// RenderQuickConfig produces a wg-quick / WireGuard-for-Windows tunnel file
// for the desired configuration. The file contains the device's PRIVATE key:
// it is written only on explicit operator request (`nexlink-agent
// export-config`) and should be deleted after importing it.
//
// It never sets DNS, routes beyond the peers' /32 AllowedIPs, or a default
// route; ValidateDesired enforces that before rendering.
func RenderQuickConfig(privateKey wgtypes.Key, listenPort int, address string, cfg DesiredConfig) (string, error) {
	if err := ValidateDesired(cfg); err != nil {
		return "", err
	}
	ip, network, err := net.ParseCIDR(address)
	if err != nil {
		return "", errors.New("render: interface address must be CIDR, e.g. 10.100.0.2/24")
	}
	_, want, _ := net.ParseCIDR(cfg.NetworkCIDR)
	if !want.Contains(ip) || network.String() != want.String() {
		return "", fmt.Errorf("render: address %s is not inside network %s", address, cfg.NetworkCIDR)
	}
	if listenPort < 1 || listenPort > 65535 {
		return "", errors.New("render: listen port out of range")
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# NexLink tunnel — network %s, config v%d. Generated by nexlink-agent export-config.\n", cfg.NetworkCIDR, cfg.Version)
	b.WriteString("# Contains this device's PRIVATE key. Import into WireGuard, then delete this file.\n")
	b.WriteString("[Interface]\n")
	fmt.Fprintf(&b, "PrivateKey = %s\n", privateKey.String())
	fmt.Fprintf(&b, "ListenPort = %d\n", listenPort)
	fmt.Fprintf(&b, "Address = %s\n", address)
	for _, p := range cfg.Peers {
		b.WriteString("\n[Peer]\n")
		fmt.Fprintf(&b, "PublicKey = %s\n", p.PublicKey)
		fmt.Fprintf(&b, "AllowedIPs = %s\n", strings.Join(p.AllowedIPs, ", "))
		if p.Endpoint != "" {
			fmt.Fprintf(&b, "Endpoint = %s\n", p.Endpoint)
		} else {
			b.WriteString("# No endpoint known yet: this side waits for the peer to connect first.\n")
		}
		if p.PersistentKeepalive > 0 {
			fmt.Fprintf(&b, "PersistentKeepalive = %d\n", int(p.PersistentKeepalive.Seconds()))
		}
	}
	return b.String(), nil
}
